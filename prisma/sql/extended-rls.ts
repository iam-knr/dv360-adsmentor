// P3-05c. Text of prisma/sql/80-extended-rls.sql: one app_enable_tenant_rls call for every model in
// prisma/schema/70..89 that has a "sandboxId" column. A test regenerates it and fails on a difference.
import { readdirSync, readFileSync } from 'node:fs';
import { join, resolve } from 'node:path';
import { parseModels, tenantModels } from '../../lib/db/schema-info';

/** Schema files owned by P3-05c: numeric prefix 70 to 89. */
export function extendedSchemaText(root = process.cwd()): string {
  const dir = resolve(root, 'prisma/schema');
  return readdirSync(dir)
    .filter((f) => f.endsWith('.prisma') && /^(7|8)\d-/.test(f))
    .sort()
    .map((f) => readFileSync(join(dir, f), 'utf8'))
    .join('\n');
}

export function renderExtendedRlsSql(root = process.cwd()): string {
  const lines = [
    '-- P3-05c. GENERATED by `npx tsx prisma/sql/generate-extended-rls.ts` from prisma/schema/70..89 (every model with a "sandboxId" column).',
    '-- A test regenerates this text and fails if it differs.',
    ...tenantModels(parseModels(extendedSchemaText(root)))
      .map((m) => m.name)
      .sort()
      .map((n) => `SELECT app_enable_tenant_rls('${n}');`),
    '',
  ];
  return lines.join('\n');
}
