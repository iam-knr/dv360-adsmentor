// Reads prisma/schema/*.prisma as text. Used by the RLS generator and by tests that enumerate the schema.
// Server and test code only; never import this from app or components.
import { readdirSync, readFileSync } from 'node:fs';
import { join, resolve } from 'node:path';

export interface ModelField {
  name: string;
  type: string;
  optional: boolean;
  list: boolean;
  attributes: string;
}

export interface ModelInfo {
  name: string;
  fields: ModelField[];
}

const SCALARS = new Set([
  'String',
  'Int',
  'BigInt',
  'Float',
  'Decimal',
  'Boolean',
  'DateTime',
  'Json',
  'Bytes',
]);

export function schemaDir(root = process.cwd()): string {
  return resolve(root, 'prisma/schema');
}

export function readSchemaText(root = process.cwd()): string {
  const dir = schemaDir(root);
  return readdirSync(dir)
    .filter((f) => f.endsWith('.prisma'))
    .sort()
    .map((f) => readFileSync(join(dir, f), 'utf8'))
    .join('\n');
}

/** Schema files of P3-05a and P3-01 only (numeric prefix 00 to 69). P3-05c adds 70 to 89 in later migrations. */
export function readCoreSchemaText(root = process.cwd()): string {
  const dir = schemaDir(root);
  return readdirSync(dir)
    .filter((f) => f.endsWith('.prisma') && Number(f.slice(0, 2)) < 70)
    .sort()
    .map((f) => readFileSync(join(dir, f), 'utf8'))
    .join('\n');
}

/** Parse model blocks. Fields only; block attributes (@@) are ignored. */
export function parseModels(text: string): ModelInfo[] {
  const models: ModelInfo[] = [];
  const blockRe = /^model\s+(\w+)\s*\{([\s\S]*?)^\}/gm;
  for (const m of text.matchAll(blockRe)) {
    const fields: ModelField[] = [];
    for (const raw of (m[2] ?? '').split('\n')) {
      const line = raw.replace(/\/\/.*$/, '').trim();
      if (!line || line.startsWith('@@')) continue;
      const f = /^(\w+)\s+(\w+)(\[\])?(\?)?\s*(.*)$/.exec(line);
      if (!f) continue;
      fields.push({
        name: f[1] as string,
        type: f[2] as string,
        list: Boolean(f[3]),
        optional: Boolean(f[4]),
        attributes: f[5] ?? '',
      });
    }
    models.push({ name: m[1] as string, fields });
  }
  return models;
}

export function parseEnums(text: string): Map<string, string[]> {
  const out = new Map<string, string[]>();
  for (const m of text.matchAll(/^enum\s+(\w+)\s*\{([\s\S]*?)^\}/gm)) {
    const values = (m[2] ?? '')
      .split('\n')
      .map((l) => l.replace(/\/\/.*$/, '').trim())
      .filter(Boolean);
    out.set(m[1] as string, values);
  }
  return out;
}

export function isScalarOrEnum(type: string, enums: Map<string, string[]>): boolean {
  return SCALARS.has(type) || enums.has(type);
}

/** Models that carry a `sandboxId` column: the tenant tables that RLS protects (data-model 2.2). */
export function tenantModels(models: ModelInfo[]): ModelInfo[] {
  return models.filter((m) => m.fields.some((f) => f.name === 'sandboxId'));
}

/** SQL that puts every tenant table under RLS (written to prisma/sql/40-rls-apply.sql). */
export function renderRlsApplySql(models: ModelInfo[]): string {
  const lines = [
    '-- P3-05a. GENERATED by `npm run db:gen-rls` from prisma/schema (every model with a "sandboxId" column).',
    '-- A test regenerates this text and fails if it differs. Tables added later call app_enable_tenant_rls in their own migration.',
    ...tenantModels(models)
      .map((m) => m.name)
      .sort()
      .map((n) => `SELECT app_enable_tenant_rls('${n}');`),
    '',
  ];
  return lines.join('\n');
}
